# make_fixture.py  --  generate the committed test fixtures.
#
# Run by hand, never by tests\build.bat and never by CI:
#
#     py -3 tests\make_fixture.py
#
# It writes tests\fixture_msml.h, tests\fixture_lzma.h and tests\fixture_mtv.h,
# which are committed. Re-run and commit the result if a fixture needs to grow
# a case.
#
# WHY THE BYTES ARE COMMITTED RATHER THAN MADE AT RUN TIME
#
# The build deliberately has no compressor of any kind. miniz comes in with
# MINIZ_NO_DEFLATE_APIS, and of the LZMA SDK only the decoder is vendored --
# 39 KB of the 400-odd files in the archive. So a harness that wants a
# compressed stream to read cannot make one; it has to be handed the bytes.
# That is a good property to keep, and this script is the price of it.
#
# THE FIXTURES ARE SYNTHETIC ON PURPOSE
#
# A slice of the real momentum\_cache, or a real demo, would be simpler and is
# not an option: both are other people's work with real ids in them, and the
# repository already refuses to carry anything of that shape (see .gitignore's
# reasoning about demos). Everything below is invented, and chosen to hit the
# paths that are otherwise only reachable on a machine with a game installed.

import json
import lzma
import os
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))


# ---------------------------------------------------------------------------
# Writing a header
# ---------------------------------------------------------------------------

def carray(name, blob):
    out = ["static const unsigned char %s[%d] = {" % (name, len(blob))]
    for i in range(0, len(blob), 12):
        out.append("    %s," % ", ".join("0x%02x" % b for b in blob[i:i + 12]))
    out.append("};")
    return "\n".join(out)


def write_header(name, guard, why, parts):
    path = os.path.join(HERE, name)
    body = ["// %s  --  generated by tests\\make_fixture.py. Do not hand-edit." % name,
            "//"]
    body += ["// " + line if line else "//" for line in why.strip().split("\n")]
    body += ["", "#ifndef %s" % guard, "#define %s" % guard, ""]
    for part in parts:
        body.append(part)
        body.append("")
    body += ["#endif // %s" % guard, ""]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(body))
    print("wrote %s" % path)


