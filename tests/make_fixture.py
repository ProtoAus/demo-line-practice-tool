def msml(obj):
    """MSML, u32 decompressed size, u32 map count, then a raw zlib stream."""
    maps = obj if isinstance(obj, list) else obj["maps"]
    body = json.dumps(obj, separators=(",", ":"), ensure_ascii=False)
    body = body.encode("utf-8")
    out = bytearray(b"MSML")
    out += len(body).to_bytes(4, "little")
    out += len(maps).to_bytes(4, "little")
    out += zlib.compress(body, 9)
    return bytes(out)


# ---------------------------------------------------------------------------
# A payload worth compressing
# ---------------------------------------------------------------------------
#
# Written as a formula rather than as bytes so that the committed header holds
# only the COMPRESSED stream. The harness computes the expected output with the
# same twelve lines and compares, which is what makes "the decoder produced the
# right bytes" a real assertion rather than "the decoder produced the bytes
# next to it in the same file".
#
# It has to be worth compressing in the specific ways the decoder can get
# wrong, so it is three things interleaved: literals it cannot predict, short
# runs of one byte, and matches a thousand bytes back. A decoder that mishandles
# long distances passes on noise alone.
#
# Keep in step with Payload() in tests\test_lzma.cpp and tests\test_mtv.cpp.

def payload(n):
    out = bytearray()
    s = 12345
    for i in range(n):
        s = (s * 1664525 + 1013904223) & 0xFFFFFFFF
        if i >= 1000 and (i // 137) % 3 == 0:
            out.append(out[i - 1000])
        elif (i // 61) % 5 == 0:
            out.append(0x41)
        else:
            out.append((s >> 24) & 0xFF)
    return bytes(out)


def valve_lzma(data, lc=3, lp=0, pb=2, dict_size=1 << 16):
    """The five property bytes and a raw LZMA1 stream, as a .mtv carries them."""
    filt = [{"id": lzma.FILTER_LZMA1, "lc": lc, "lp": lp, "pb": pb,
             "dict_size": dict_size}]
    c = lzma.LZMACompressor(format=lzma.FORMAT_RAW, filters=filt)
    comp = c.compress(data) + c.flush()

    props = bytes([(pb * 5 + lp) * 9 + lc]) + dict_size.to_bytes(4, "little")

    # Decode it back exactly the way wrpath_extract.py's decompress_body does,
    # so a fixture that the reference cannot read never reaches the repository.
    d = lzma.LZMADecompressor(format=lzma.FORMAT_RAW, filters=filt)
    back = d.decompress(comp, len(data))
    assert back == data, "fixture does not round-trip through the reference"
    return props, comp


# ---------------------------------------------------------------------------
# A demo
# ---------------------------------------------------------------------------
#
# The whole container, at both of the JSON offsets seen in the wild. The two
# differ by one byte of padding, which is the entire reason the reference
# locates the blob by scanning instead of reading it from a constant -- so a
# fixture that only had one of them would not test the thing the scan exists
# for.
#
# The run-stats JSON is deliberately FLAT, with no nested object, so that the
# first '{' at or after 0xB0 is the real one. The compressed body begins inside
# the same window and contains braces of its own, which is true of every real
# demo too -- the locator's job is to stop at the first one that validates, and
# a fixture where no other candidate existed would not be asking it to.

MTV_MAP = "surf_fixture"
MTV_HASH = "0123456789abcdef0123456789abcdef01234567"
MTV_PLAYER = "fixture player"
MTV_STEAMID = 0x0110000112345678
MTV_DATE_MS = 1700000000123
MTV_TICKS = 4083
MTV_BODY_BYTES = 4096

MTV_JSON = ('{"maxHorizontalSpeed":2500.5,"effectiveStartVelocity":320.25,'
            '"jumps":41,"strafes":812,"note":"synthetic, see make_fixture.py"}')


def mtv(json_at):
    import struct
    head = bytearray(b"\0" * json_at)
    head[0:4] = b"MMTV"
    struct.pack_into("<I", head, 0x04, 2)
    struct.pack_into("<q", head, 0x08, MTV_DATE_MS)
    head[0x10:0x10 + len(MTV_MAP)] = MTV_MAP.encode()
    head[0x50:0x50 + len(MTV_HASH)] = MTV_HASH.encode()
    head[0x79] = 1                                  # gamemode: surf
    struct.pack_into("<f", head, 0x7B, 0.015)
    struct.pack_into("<Q", head, 0x7F, MTV_STEAMID)
    head[0x87:0x87 + len(MTV_PLAYER)] = MTV_PLAYER.encode()
    head[0xA7] = 2                                  # track type: bonus
    head[0xA8] = 3                                  # track num
    struct.pack_into("<d", head, 0xA9, 61.25)
    struct.pack_into("<I", head, 0xB1, MTV_TICKS)

    blob = MTV_JSON.encode()
    struct.pack_into("<I", head, json_at - 4, len(blob))

    data = payload(MTV_BODY_BYTES)
    props, comp = valve_lzma(data)

    out = bytearray(head)
    out += blob
    out += b"LZMA"
    out += struct.pack("<II", len(data), len(comp))
    out += props
    out += comp

    # The promises the harness is written against. Note what is NOT promised:
    # that there is only one '{' in the window. The compressed body starts well
    # before 0x200 and a compressed stream contains whatever bytes it contains,
    # exactly as a real demo's does. What matters is that the FIRST brace at or
    # after 0xB0 is the real one, so the locator stops on it and the padding
    # before it holds none.
    assert len(out) >= 0x200
    assert out.index(b"{", 0xB0) == json_at
    return bytes(out)


